def wrap(text, width=100):
    out = []
    for para in text.split("\n"):
        out.append("" if para.strip() == "" else "\n".join(textwrap.wrap(para, width=width) or [""]))
    return "\n".join(out)


def text_page(pdf, title, body, fontsize=9.3):
    fig = plt.figure(figsize=(8.5, 11))
    fig.text(0.07, 0.95, title, fontsize=15, fontweight="bold", va="top")
    fig.text(0.07, 0.90, body, fontsize=fontsize, va="top", ha="left", family="sans-serif")
    pdf.savefig(fig)
    plt.close(fig)


def figure_page(pdf, png_path, title, caption):
    fig = plt.figure(figsize=(8.5, 11))
    img = mpimg.imread(png_path)
    ax_img = fig.add_axes([0.05, 0.28, 0.9, 0.66])
    ax_img.imshow(img)
    ax_img.axis("off")
    fig.text(0.07, 0.97, title, fontsize=14, fontweight="bold", va="top")
    fig.text(0.07, 0.20, wrap(caption, 100), fontsize=10, va="top")
    pdf.savefig(fig)
    plt.close(fig)


def table_page(pdf, title, df, note=""):
    fig = plt.figure(figsize=(11, 8.5))
    fig.text(0.05, 0.95, title, fontsize=14, fontweight="bold", va="top")
    ax = fig.add_axes([0.03, 0.10, 0.94, 0.80])
    ax.axis("off")
    tbl = ax.table(cellText=df.values, colLabels=df.columns, loc="center", cellLoc="left")
    tbl.auto_set_font_size(False)
    tbl.set_fontsize(7.5)
    tbl.scale(1, 1.5)
    for j in range(len(df.columns)):
        tbl.auto_set_column_width(j)
    if note:
        fig.text(0.05, 0.06, wrap(note, 135), fontsize=8, va="top", style="italic")
    pdf.savefig(fig)
    plt.close(fig)


